SeekerMatchPage demoSeekerPage() {
  final visible = [
    for (final seed in _seeds)
      if (seed.discoverable)
        SeekerMatch(
          requirementId: seed.id,
          displayName: seed.name,
          city: seed.city,
          localities: seed.localities,
          budgetMinInr: seed.budgetMin,
          budgetMaxInr: seed.budgetMax,
          roomType: seed.roomType,
          seekerKind: seed.kind,
          aboutMe: seed.about,
          profession: seed.profession,
          listingTitle: '2 BHK in Koramangala',
          matchPercent: requirementListingMatch(
            listingCity: demoMatchCity,
            listingLocality: demoMatchLocality,
            rentInr: demoMatchRent,
            propertyType: 'apartment',
            furnishing: 'semi_furnished',
            listingAmenities: const [
              'wifi',
              'ac',
              'security',
              'washing_machine',
            ],
            availableFrom: DateTime(2026, 11),
            requirementCity: seed.city,
            requirementLocalities: seed.localities,
            budgetMinInr: seed.budgetMin,
            budgetMaxInr: seed.budgetMax,
            roomType: seed.roomType,
            propertyTypes: const ['apartment'],
            requirementFurnishing: seed.furnishing,
            requirementAmenities: seed.amenities,
            moveInDate: seed.moveIn,
          ),
        ),
  ]..sort((a, b) => b.matchPercent.compareTo(a.matchPercent));
  return SeekerMatchPage(seekers: visible, basis: demoMatchBasis);
}

int demoSeekerCountIncludingHidden() => _seeds.length;
