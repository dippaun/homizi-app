FinderPerson _person({
  required String id,
  required String name,
  required int age,
  required String gender,
  required int photo,
  required String group,
  required String field,
  required String profession,
  required String city,
  required List<String> localities,
  required int budgetMin,
  required int budgetMax,
  required DateTime moveIn,
  required String food,
  required String smoking,
  required String drinking,
  required String pets,
  required int cleanliness,
  required List<String> languages,
  required String hometown,
  required String education,
  required String lookingFor,
  required String about,
  required String quote,
  String social = 'balanced',
  String sleep = 'early',
  String wfh = 'hybrid',
  bool verified = false,
  bool likesYou = false,
  bool online = false,
}) {
  final avatar = 'assets/avatars/avatar_0$photo.webp';
  return FinderPerson(
    seeker: RoommateSeeker(
      id: 'b1113000-0000-4000-8000-000000000$id',
      name: name,
      age: age,
      profession: profession,
      photoRef: avatar,
      likesYou: likesYou,
      trust: UserBadges(aadhaarVerified: verified, faceVerified: verified),
      traits: RoommateTraits(
        city: city,
        localities: localities,
        budgetMinInr: budgetMin,
        budgetMaxInr: budgetMax,
        moveIn: moveIn,
        gender: gender,
        genderPreference: 'any',
        occupancy: 'shared',
        food: food,
        smoking: smoking,
        pets: pets,
        sleep: sleep,
        cleanliness: cleanliness,
        social: social,
        wfh: wfh,
        cooking: 'often',
        guests: 'rare',
        languages: languages,
        hobbies: const ['reading'],
        thoughts: quote,
      ),
    ),
    group: group,
    field: field,
    drinking: drinking,
    lookingFor: lookingFor,
    education: education,
    hometown: hometown,
    about: about,
    gallery: [avatar, ...finderRoomPhotos],
    online: online,
  );
}
