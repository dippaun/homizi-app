/// City first, then the localities offered as chips for that city.
List<String> roomieLocalities(String city) {
  if (city == 'Delhi') {
    return _delhiLocalities;
  }
  final names = [
    for (final place in localitySeed)
      if (place.city == city) place.name,
  ];
  if (names.length <= 8) {
    return names;
  }
  return names.sublist(0, 8);
}

RoomiePerson personById(String id) {
  for (final person in roomiePeople) {
    if (person.id == id) {
      return person;
    }
  }
  return roomiePeople.first;
}

RoomieFlat? flatById(String id) {
  for (final flat in roomieFlats) {
    if (flat.id == id) {
      return flat;
    }
  }
  return null;
}

